/** 본문 매칭용: 긴 표기부터 검사하도록 정렬한 [표기, entry] 목록 */
export const GLOSSARY_MATCHERS: { text: string; entry: GlossaryEntry }[] = GLOSSARY.flatMap((e) =>
  [e.term, ...e.aliases].map((text) => ({ text, entry: e })),
).sort((a, b) => b.text.length - a.text.length);

export function getGlossaryEntry(id: string): GlossaryEntry | undefined {
  return GLOSSARY.find((e) => e.id === id);
}
