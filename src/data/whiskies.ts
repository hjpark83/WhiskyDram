const BY_ID = new Map(WHISKIES.map((w) => [w.id, w]));

export function getWhisky(id: string): Whisky | undefined {
  return BY_ID.get(id);
}

export function getWhiskies(ids: string[]): Whisky[] {
  return ids.map((id) => BY_ID.get(id)).filter((w): w is Whisky => Boolean(w));
}
