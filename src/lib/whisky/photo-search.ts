import type { Whisky } from "@/lib/whisky/types";

/**
 * "이 병 실물은 어떻게 생겼나" → 구글 이미지 검색으로 보내요.
 *
 * ## 왜 사진을 직접 안 넣나
 *
 * 판매 사이트·수입사의 제품 이미지는 그 회사 자산이라 가져다 쓸 수 없어요.
 * 그래서 병은 3D 로 그리고 있는데, 잘 그려도 **실물은 아니에요.** "마트에서
 * 본 그 병이 이게 맞나" 를 확인하려면 실물 사진을 이길 수 없어요.
 *
 * ## 검색으로 보내는 건 괜찮아요
 *
 * 우리가 사진을 복제·호스팅·핫링크하는 게 아니라 **검색 결과로 보내는 것**뿐이라
 * 저작권 문제가 없어요. 사용자는 한 번 눌러서 수십 장을 보고, 우리는 남의 자산을
 * 건드리지 않아요. 사용자가 직접 찍어 올린 사진(`whisky_photos`)이 쌓이면
 * 그게 우선이고, 이 링크는 아직 사진이 없는 병의 빈자리를 메워요.
 *
 * ## 검색어를 왜 이렇게 만드나
 *
 *  - **영문 이름**으로 물어봐요. 한글 이름으로는 국내 블로그 글에 섞인 사진만
 *    나오고, 국내에 정식 수입되지 않은 병(파리에서 마신 프렌치 위스키처럼)은
 *    결과가 아예 없어요.
 *  - **`whisky bottle` 을 붙여요.** Macallan·Glenlivet 처럼 지명이기도 한
 *    이름이 많아서, 안 붙이면 풍경 사진이 먼저 나와요. `bottle` 은 잔·바 사진
 *    말고 병 사진 쪽으로 당겨줘요.
 *  - `tbm=isch` 가 이미지 탭이에요.
 */
export function photoSearchUrl(w: Pick<Whisky, "name">): string {
  const q = encodeURIComponent(`${w.name} whisky bottle`);
  return `https://www.google.com/search?q=${q}&tbm=isch`;
}
